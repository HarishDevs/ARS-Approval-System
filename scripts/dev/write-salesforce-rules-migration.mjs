// D-205: writes the migration that loads docs/AI-RULES-SALESFORCE.md as the
// Salesforce chat's AI Rules (only when none exist). Run after editing the
// guide, before the migration has been applied anywhere:
//   node scripts/dev/write-salesforce-rules-migration.mjs
import fs from "node:fs";

const SOURCE = "docs/AI-RULES-SALESFORCE.md";
const TARGET = "database/migrations/202610261500_ai_rules_salesforce.sql";
const MAX_CHARS = 20000; // server/ai/assistant.ts MAX_RULES_CHARS

const guide = fs.readFileSync(SOURCE, "utf8").replace(/\r\n/g, "\n").trim();
if (guide.length > MAX_CHARS) throw new Error(`${SOURCE} is ${guide.length} characters; AI Rules allow ${MAX_CHARS}.`);
// The migration runner treats a line starting with "--" as a comment or marker.
if (guide.split("\n").some((line) => line.trim().startsWith("--"))) throw new Error(`${SOURCE} has a line starting with "--".`);
const literal = `'${guide.replace(/\\/g, "\\\\").replace(/'/g, "''")}'`;

const sql = `-- D-205 (owner: "with all the available data in Salesforce train the Pico Bot
-- and add all the training data in AI Rules for Salesforce"): the Salesforce
-- guide (${SOURCE}) becomes the Salesforce chat rules, only when none were
-- written yet, so rules the IT team saved are never replaced. Recorded as
-- saved by the first Super Admin; a database without users (a fresh test
-- database) gets nothing. Generated by scripts/dev/write-salesforce-rules-migration.mjs.
-- @begin
INSERT INTO ai_rules (chat_mode, content, updated_by)
SELECT 'SALESFORCE', ${literal}, u.id
FROM users u
JOIN user_roles ur ON ur.user_id = u.id
JOIN roles r ON r.id = ur.role_id
WHERE r.code = 'SUPER_ADMIN'
  AND NOT EXISTS (SELECT 1 FROM ai_rules WHERE chat_mode = 'SALESFORCE')
ORDER BY u.id
LIMIT 1
-- @end
`;
fs.writeFileSync(TARGET, sql);
console.log(`Wrote ${TARGET} (${guide.length} characters of rules).`);
